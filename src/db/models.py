"""
Database models for email replier.

Defines SQLAlchemy models for database tables:
- Email  : inbound candidate emails (written by collaborator's Gmail puller)
- Reply  : outgoing replies generated by our pipeline
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import Boolean, Column, Integer, Text, TIMESTAMP, VARCHAR, JSON
from sqlalchemy.dialects.postgresql import UUID as PostgresUUID
from sqlalchemy.sql import func
from sqlalchemy.ext.declarative import declarative_base

Base = declarative_base()


class Email(Base):
    """Email model for storing inbound candidate emails."""

    __tablename__ = "emails"

    # Primary key
    id = Column(
        PostgresUUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True
    )

    # Email identifiers
    email_id = Column(
        VARCHAR(255),
        unique=True,
        nullable=False,
        index=True,
        comment="Unique email identifier"
    )

    message_id = Column(
        VARCHAR(255),
        nullable=True,
        comment="Gmail message ID"
    )
    
    thread_id = Column(
        VARCHAR(255),
        nullable=True,
        index=True,
        comment="Gmail thread ID for conversation tracking"
    )
    # Email content
    subject = Column(
        Text,
        nullable=True,
        comment="Email subject"
    )

    from_addr = Column(
        VARCHAR(255),
        nullable=True,
        comment="Sender email address"
    )

    to_addr = Column(
        VARCHAR(255),
        nullable=False,
        comment="Recipient email address"
    )

    date = Column(
        TIMESTAMP(timezone=True),
        nullable=True,
        comment="Email date/time"
    )

    body = Column(
        Text,
        nullable=True,
        comment="Email body content"
    )
    
    # Processing status
    status = Column(
        VARCHAR(50),
        default="pending",
        nullable=False,
        comment="Processing status: pending, processing, processed, irrelevant, error"
    )

    # Thread history (JSON list)
    history = Column(
        JSON,
        default=list,
        nullable=False,
        comment="Conversation/thread history records",
    )

    # Timestamps
    created_at = Column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        nullable=False,
        comment="Record creation time"
    )

    updated_at = Column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
        comment="Record update time"
    )

    def __repr__(self) -> str:
        return f"<Email(id={self.id}, email_id={self.email_id}, subject={self.subject[:50] if self.subject else ''})>"

    def to_dict(self) -> dict:
        """Convert model to dictionary."""
        return {
            "id": str(self.id),
            "email_id": self.email_id,
            "message_id": self.message_id,
            "thread_id": self.thread_id,
            "subject": self.subject,
            "from_addr": self.from_addr,
            "to_addr": self.to_addr,
            "date": self.date.isoformat() if self.date else None,
            "body": self.body,
            "status": self.status,
            "history": self.history or [],
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }


class Reply(Base):
    """Reply model for storing outgoing replies generated by our pipeline."""

    __tablename__ = "replies"

    # Primary key
    id = Column(
        PostgresUUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True
    )

    # Links to emails table
    email_id = Column(
        VARCHAR(255),
        nullable=False,
        index=True,
        comment="Links to emails.email_id"
    )

    thread_id = Column(
        VARCHAR(255),
        nullable=True,
        comment="Thread reference"
    )

    # Reply addresses
    from_addr = Column(
        VARCHAR(255),
        nullable=True,
        comment="Recruiter email address"
    )

    to_addr = Column(
        VARCHAR(255),
        nullable=True,
        comment="Candidate email address"
    )

    # Reply content
    subject = Column(
        Text,
        nullable=True,
        comment="Reply subject line"
    )

    body = Column(
        Text,
        nullable=True,
        comment="Reply email body (plain text)"
    )

    # Classification fields
    intent_label = Column(
        VARCHAR(255),
        nullable=True,
        comment="Intent bucket label"
    )

    profile_type = Column(
        VARCHAR(100),
        nullable=True,
        comment="Candidate profile type"
    )

    sender_name = Column(
        VARCHAR(255),
        nullable=True,
        comment="Recruiter full name"
    )

    detected_intents = Column(
        JSON,
        nullable=True,
        comment="Full multi-intent classification from intent classifier",
    )

    # Timestamps
    sent_at = Column(
        TIMESTAMP(timezone=True),
        nullable=True,
        comment="When the reply was sent"
    )

    created_at = Column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        nullable=False,
        comment="Record creation time"
    )

    def __repr__(self) -> str:
        return f"<Reply(id={self.id}, email_id={self.email_id})>"

    def to_dict(self) -> dict:
        """Convert model to dictionary."""
        return {
            "id": str(self.id),
            "email_id": self.email_id,
            "thread_id": self.thread_id,
            "from_addr": self.from_addr,
            "to_addr": self.to_addr,
            "subject": self.subject,
            "body": self.body,
            "intent_label": self.intent_label,
            "profile_type": self.profile_type,
            "sender_name": self.sender_name,
            "detected_intents": self.detected_intents,
            "sent_at": self.sent_at.isoformat() if self.sent_at else None,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class Log(Base):
    """Log model for storing per-email pipeline logs."""

    __tablename__ = "logs"

    id = Column(
        PostgresUUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )

    email_id = Column(
        VARCHAR(255),
        nullable=False,
        index=True,
        comment="Links to emails.email_id",
    )

    subject = Column(Text, nullable=True)
    from_addr = Column(VARCHAR(255), nullable=True)
    to_addr = Column(VARCHAR(255), nullable=True)

    intent_id = Column(Integer, nullable=True)
    intent_label = Column(VARCHAR(255), nullable=True)
    profile_type = Column(VARCHAR(100), nullable=True)

    is_relevant = Column(Boolean, nullable=True)
    status = Column(VARCHAR(50), nullable=True)
    sent = Column(Boolean, nullable=True)
    sent_at = Column(TIMESTAMP(timezone=True), nullable=True)
    error = Column(Text, nullable=True)

    payload = Column(JSON, nullable=False, default=dict, comment="Full log record JSON")

    created_at = Column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at = Column(
        TIMESTAMP(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


